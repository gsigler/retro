/**
 * Returns a deterministic question index based on a seed string.
 * Same seed always returns the same question.
 */
export function seededQuestionIndex(seed: string, offset = 0): number {
  let hash = 0
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i)
    hash |= 0
  }
  const index =
    (((hash + offset) % ICEBREAKER_QUESTIONS.length) +
      ICEBREAKER_QUESTIONS.length) %
    ICEBREAKER_QUESTIONS.length
  return index
}
